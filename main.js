// 輔助函式：Google 雲端硬碟連結轉換為直接顯示的高畫質網址
function convertDriveUrl(url) {
  if (!url || url.trim() === '') return 'https://images.unsplash.com/photo-1511795409834-ef04bbd61622?auto=format&fit=crop&q=80&w=800';
  if (url.includes('drive.google.com')) {
    const match = url.match(/\/d\/([a-zA-Z0-9_-]+)/) || url.match(/id=([a-zA-Z0-9_-]+)/);
    if (match && match[1]) {
      return `https://drive.google.com/thumbnail?sz=w1280&id=${match[1]}`;
    }
  }
  return url;
}

