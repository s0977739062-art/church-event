// 日期解析輔助函式
function parseEventDate(dateStr) {
  if (!dateStr) return new Date(0);
  const clean = dateStr.trim();
  if (clean.includes('-') || clean.split('/').length === 3) {
    return new Date(clean.replace(/-/g, '/'));
  }
  return new Date(`${currentYear}/${clean}`);
}

// 渲染畫面的主函式
function renderEvents() {
  const filteredEvents = allEvents
    .filter(event => {
      const eventDate = parseEventDate(event.date);
      const isNotExpired = !isNaN(eventDate.getTime()) && (eventDate.setHours(23, 59, 59, 999) >= today.getTime());
      
      let matchesCategory = false;
      if (currentCategory === '全部') {
        matchesCategory = true;
      } else {
        matchesCategory = (event.category === currentCategory);
      }

      return isNotExpired && matchesCategory;
    })
    .sort((a, b) => {
      const dateA = parseEventDate(a.date);
      const dateB = parseEventDate(b.date);
      return dateA - dateB;
    });

  if (filteredEvents.length === 0) {
    container.innerHTML = `<div class="col-12 text-muted py-5 text-center fs-5">目前這個分類沒有進行中的活動</div>`;
    return;
  }

  container.innerHTML = filteredEvents.map((event, index) => {
    let badgeClass = 'bg-light text-dark border';
    if (event.status === '報名中' || event.status === '訂便當') badgeClass = 'bg-dark text-white';

    const imageUrl = convertDriveUrl(event.image);

    return `
    <div class="col-md-4">
      <div class="card h-100 border-0 shadow-sm rounded-4 overflow-hidden transition-hover bg-white position-relative">
        
        <!-- 管理員專屬：編輯與刪除小按鈕 -->
        <div class="admin-card-actions">
          <button class="btn-action-pill btn-edit" data-idx="${index}">✏️ 編輯</button>
          <button class="btn-action-pill btn-action-delete btn-delete" data-idx="${index}">🗑️ 刪除</button>
        </div>

        <img src="${imageUrl}" class="card-img-top card-cover-img" alt="${event.title}">
        <div class="card-body p-4 d-flex flex-column">
          <div class="mb-2">
            <span class="text-muted fw-semibold small">
              <i class="bi bi-calendar3 me-1"></i> ${event.displayDate}
            </span>
          </div>
          
          <h5 class="fw-bold mb-3">${event.title}</h5>
          
          <div class="mt-auto d-flex justify-content-between align-items-center">
            <span class="badge ${badgeClass} px-2 py-1 rounded-pill">${event.status}</span>
            <a href="${event.link}" target="_blank" class="text-dark text-decoration-none fw-bold small">
              立即報名 <i class="bi bi-arrow-right-short fs-5 align-middle"></i>
            </a>
          </div>
        </div>
      </div>
    </div>
    `;
  }).join('');

  container.querySelectorAll('.btn-edit').forEach((btn, idx) => {
    btn.addEventListener('click', () => startEdit(filteredEvents[idx]));
  });
  container.querySelectorAll('.btn-delete').forEach((btn, idx) => {
    btn.addEventListener('click', () => startDelete(filteredEvents[idx]));
  });
}

// 自動檢查並從 Google 試算表刪除過期活動
async function cleanExpiredEventsInSheet() {
  if (!isAdmin) return;

  const expiredItems = allEvents.filter(e => {
    const eDate = parseEventDate(e.date);
    return !isNaN(eDate.getTime()) && (eDate.setHours(23, 59, 59, 999) < today.getTime());
  }).sort((a, b) => b._rowIndex - a._rowIndex);

  if (expiredItems.length === 0) return;

  for (const item of expiredItems) {
    try {
      await fetch(GAS_API_URL, {
        method: "POST",
        mode: "cors",
        headers: { "Content-Type": "text/plain;charset=utf-8" },
        body: JSON.stringify({
          action: "delete",
          rowIndex: item._rowIndex
        })
      });
    } catch (err) {
      console.error("自動清理失敗：", err);
    }
  }

  showToast(`已自動清理 ${expiredItems.length} 筆過期活動！`);
  setTimeout(loadEventsFromSheet, 1000);
}

// 動態更新分類標籤按鈕
function syncCategoryButtons() {
  const categories = new Set(['全部']);
  allEvents.forEach(e => {
    if (e.category && e.category.trim()) categories.add(e.category.trim());
  });

  categoryFilter.innerHTML = '';
  categories.forEach(cat => {
    const btn = document.createElement('button');
    btn.className = `btn rounded-pill px-4 py-2 fw-semibold ${cat === currentCategory ? 'btn-dark text-white shadow-sm' : 'btn-light text-muted'}`;
    btn.textContent = cat;
    btn.setAttribute('data-category', cat);
    btn.addEventListener('click', () => {
      currentCategory = cat;
      syncCategoryButtons();
      renderEvents();
    });
    categoryFilter.appendChild(btn);
  });
}

// 從 Google 試算表載入資料
async function loadEventsFromSheet() {
  try {
    const csvUrl = `https://docs.google.com/spreadsheets/d/${SHEET_ID}/export?format=csv&_t=${Date.now()}`;
    const response = await fetch(csvUrl);
    const csvText = await response.text();

    const lines = csvText.split('\n');
    allEvents = [];

    for (let i = 1; i < lines.length; i++) {
      const line = lines[i].trim();
      if (!line) continue;

      const row = [];
      let match;
      const regex = /(?:,|\n|^)("(?:(?:"")*[^"]*)*"|[^",\n]*|(?:\n|$))/g;
      while ((match = regex.exec(line)) && match[0] !== "") {
        let val = match[1] || "";
        val = val.replace(/^"|"$/g, "").replace(/""/g, '"').trim();
        row.push(val);
      }

      if (row.length >= 7) {
        allEvents.push({
          _rowIndex: i + 1,
          date: row[0],
          displayDate: row[1],
          title: row[2],
          category: row[3],
          status: row[4],
          link: row[5],
          image: row[6]
        });
      }
    }

    syncCategoryButtons();
    renderEvents();

    if (isAdmin) {
      cleanExpiredEventsInSheet();
    }
  } catch (error) {
    console.error('讀取試算表失敗：', error);
    container.innerHTML = `<div class="col-12 text-danger py-4 text-center">無法載入活動資料，請確認試算表共用設定已開啟。</div>`;
  }
}

