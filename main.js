async function startDelete(item) {
  const confirmDelete = confirm(`確定要永久刪除活動「${item.title}」嗎？\n此動作將同步從 Google 試算表中移除。`);
  if (!confirmDelete) return;

  try {
    await fetch(GAS_API_URL, {
      method: "POST",
      mode: "cors",
      headers: { "Content-Type": "text/plain;charset=utf-8" },
      body: JSON.stringify({
        action: "delete",
        rowIndex: item._rowIndex
      })
    });

    showToast("✓ 活動已成功刪除！");
    setTimeout(loadEventsFromSheet, 1000);
  } catch (err) {
    console.error("刪除失敗：", err);
    alert("刪除失敗，請檢查網路連線。");
  }
}

